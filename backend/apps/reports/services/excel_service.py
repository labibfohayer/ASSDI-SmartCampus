import io
from typing import Any, Dict, List, Optional
import openpyxl
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

from apps.reports.constants import REPORT_NAMES, ReportType


class ExcelExportService:
    # Color palette
    HEADER_BG = "1B4D3E"       # As-Sunnah Deep Forest Green
    TABLE_HEADER_BG = "2D6A4F" # Medium Forest Green
    ZEBRA_BG = "F7FBF9"        # Very light greenish tint
    WHITE = "FFFFFF"
    DARK_TEXT = "1F2937"

    @classmethod
    def generate_excel(
        cls,
        report_type: str,
        data: Dict[str, Any],
        user_name: str = "Staff",
        filters: Optional[Dict[str, Any]] = None,
    ) -> io.BytesIO:
        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = "Report"
        ws.views.sheetView[0].showGridLines = True

        report_title = REPORT_NAMES.get(report_type, report_type.replace("_", " ").title())

        # Styling Definitions
        title_font = Font(name="Arial", size=14, bold=True, color=cls.WHITE)
        title_fill = PatternFill(start_color=cls.HEADER_BG, end_color=cls.HEADER_BG, fill_type="solid")

        meta_font = Font(name="Arial", size=9, italic=True, color="4B5563")
        tbl_hdr_font = Font(name="Arial", size=10, bold=True, color=cls.WHITE)
        tbl_hdr_fill = PatternFill(start_color=cls.TABLE_HEADER_BG, end_color=cls.TABLE_HEADER_BG, fill_type="solid")

        regular_font = Font(name="Arial", size=10, color=cls.DARK_TEXT)
        zebra_fill = PatternFill(start_color=cls.ZEBRA_BG, end_color=cls.ZEBRA_BG, fill_type="solid")

        thin_border = Border(
            left=Side(style="thin", color="D1D5DB"),
            right=Side(style="thin", color="D1D5DB"),
            top=Side(style="thin", color="D1D5DB"),
            bottom=Side(style="thin", color="D1D5DB"),
        )

        align_center = Alignment(horizontal="center", vertical="center", wrap_text=True)
        align_left = Alignment(horizontal="left", vertical="center", wrap_text=True)
        align_right = Alignment(horizontal="right", vertical="center")

        # 1. Header Banner
        ws.merge_cells("A1:K1")
        cell_a1 = ws["A1"]
        cell_a1.value = "As-Sunnah Skill Development Institute (ASSDI)"
        cell_a1.font = title_font
        cell_a1.fill = title_fill
        cell_a1.alignment = align_center
        ws.row_dimensions[1].height = 28

        ws.merge_cells("A2:K2")
        cell_a2 = ws["A2"]
        cell_a2.value = f"{report_title}"
        cell_a2.font = Font(name="Arial", size=12, bold=True, color="1B4D3E")
        cell_a2.alignment = align_center
        ws.row_dimensions[2].height = 22

        # 2. Metadata Block
        ws["A3"] = f"Generated By: {user_name}"
        ws["A3"].font = meta_font
        ws["E3"] = f"Filters: {filters if filters else 'All'}"
        ws["E3"].font = meta_font

        current_row = 5

        # 3. Report-Specific Body
        headers: List[str] = []
        rows: List[List[Any]] = []

        if report_type == ReportType.DAILY_ATTENDANCE:
            ws.cell(row=current_row, column=1, value=f"Date: {data.get('report_date')} | Sessions: {data.get('total_sessions')} | Overall Attendance: {data.get('attendance_percentage', 'N/A')}%").font = Font(bold=True)
            current_row += 2
            headers = ["Session ID", "Batch", "Subject", "Topic", "Teacher", "Start", "End", "Present", "Late", "Absent", "Leave", "Total", "Attendance %"]
            for s in data.get("sessions", []):
                rows.append([
                    s.get("session_id"),
                    s.get("batch_name"),
                    s.get("subject_name"),
                    s.get("topic_title"),
                    s.get("teacher_name"),
                    s.get("start_time"),
                    s.get("end_time"),
                    s.get("present_count"),
                    s.get("late_count"),
                    s.get("absent_count"),
                    s.get("approved_leave_count"),
                    s.get("total_records"),
                    f"{s.get('attendance_percentage', 0.0)}%" if s.get("attendance_percentage") is not None else "N/A",
                ])

        elif report_type == ReportType.DAILY_LEARNING_PROGRESS:
            ws.cell(row=current_row, column=1, value=f"Date: {data.get('report_date')} | Feedbacks: {data.get('total_feedbacks')} | Avg Rating: {data.get('average_rating')} / 5 ({data.get('average_percentage')}%)").font = Font(bold=True)
            current_row += 2
            headers = ["Session ID", "Batch", "Subject", "Topic", "Teacher", "Feedbacks", "Pending", "Avg Rating", "Avg %", "Needs Help"]
            for s in data.get("sessions", []):
                rows.append([
                    s.get("session_id"),
                    s.get("batch_name"),
                    s.get("subject_name"),
                    s.get("topic_title"),
                    s.get("teacher_name"),
                    s.get("feedback_count"),
                    s.get("pending_feedback_count"),
                    s.get("average_rating") if s.get("average_rating") is not None else "N/A",
                    f"{s.get('average_percentage')}%" if s.get("average_percentage") is not None else "N/A",
                    s.get("needs_help_count"),
                ])

        elif report_type == ReportType.WEEKLY_PROGRESS:
            period = data.get("period", {})
            att_s = data.get("attendance_summary", {})
            learn_s = data.get("learning_summary", {})
            ws.cell(row=current_row, column=1, value=f"Period: {period.get('start_date')} to {period.get('end_date')} | Classes: {data.get('total_classes')} | Attendance: {att_s.get('attendance_percentage')}% | Learning: {learn_s.get('average_percentage')}%").font = Font(bold=True)
            current_row += 2
            headers = ["Date", "Day", "Classes", "Attendance %", "Average Rating", "Average %"]
            for d in data.get("daily_breakdown", []):
                rows.append([
                    d.get("date"),
                    d.get("day_name"),
                    d.get("classes_count"),
                    f"{d.get('attendance_percentage')}%" if d.get("attendance_percentage") is not None else "N/A",
                    d.get("average_rating") if d.get("average_rating") is not None else "N/A",
                    f"{d.get('average_percentage')}%" if d.get("average_percentage") is not None else "N/A",
                ])

        elif report_type == ReportType.MONTHLY_STUDENT_PERFORMANCE:
            ws.cell(row=current_row, column=1, value=f"Month: {data.get('year')}-{data.get('month'):02d} | Batch: {data.get('batch_name')} | Students: {data.get('total_students')}").font = Font(bold=True)
            current_row += 2
            headers = ["Student ID", "Reg No", "Student Name", "Phone", "Sessions", "Present", "Late", "Absent", "Leave", "Attendance %", "Feedbacks", "Avg Rating", "Avg %", "Help Requests", "Status"]
            for st in data.get("students", []):
                rows.append([
                    st.get("student_id_number"),
                    st.get("registration_no"),
                    st.get("student_name"),
                    st.get("phone"),
                    st.get("total_sessions"),
                    st.get("present_count"),
                    st.get("late_count"),
                    st.get("absent_count"),
                    st.get("approved_leave_count"),
                    f"{st.get('attendance_percentage')}%" if st.get("attendance_percentage") is not None else "N/A",
                    st.get("feedback_count"),
                    st.get("average_rating") if st.get("average_rating") is not None else "N/A",
                    f"{st.get('average_percentage')}%" if st.get("average_percentage") is not None else "N/A",
                    st.get("help_requests_count"),
                    st.get("status"),
                ])

        elif report_type == ReportType.BATCH_WISE_PERFORMANCE:
            headers = ["Batch ID", "Batch Name", "Batch #", "Course", "Campus", "Status", "Students", "Total Classes", "Attendance %", "Avg Rating", "Avg %", "Help Requests", "Pending HR"]
            for b in data.get("batches", []):
                rows.append([
                    b.get("batch_id"),
                    b.get("batch_name"),
                    b.get("batch_number"),
                    b.get("course_name"),
                    b.get("campus_name"),
                    b.get("status"),
                    b.get("student_count"),
                    b.get("total_classes"),
                    f"{b.get('attendance_percentage')}%" if b.get("attendance_percentage") is not None else "N/A",
                    b.get("average_rating") if b.get("average_rating") is not None else "N/A",
                    f"{b.get('average_percentage')}%" if b.get("average_percentage") is not None else "N/A",
                    b.get("total_help_requests"),
                    b.get("pending_help_requests"),
                ])

        elif report_type == ReportType.TOPIC_WISE_UNDERSTANDING:
            headers = ["Topic ID", "Topic Title", "Subject", "Course", "Sessions", "Feedbacks", "Avg Rating", "Avg %", "Needs Help"]
            for t in data.get("topics", []):
                rows.append([
                    t.get("topic_id"),
                    t.get("topic_title"),
                    t.get("subject_name"),
                    t.get("course_name"),
                    t.get("total_sessions"),
                    t.get("total_feedbacks"),
                    t.get("average_rating") if t.get("average_rating") is not None else "N/A",
                    f"{t.get('average_percentage')}%" if t.get("average_percentage") is not None else "N/A",
                    t.get("needs_help_count"),
                ])

        elif report_type == ReportType.TEACHER_WISE:
            headers = ["Teacher Name", "Login ID", "Phone", "Email", "Assigned Batches", "Classes Conducted", "Attendance %", "Avg Rating", "Avg %", "HR Received", "HR Resolved", "HR Pending"]
            for t in data.get("teachers", []):
                rows.append([
                    t.get("teacher_name"),
                    t.get("login_id"),
                    t.get("phone"),
                    t.get("email"),
                    t.get("assigned_batches_count"),
                    t.get("classes_conducted"),
                    f"{t.get('attendance_percentage_in_classes')}%" if t.get("attendance_percentage_in_classes") is not None else "N/A",
                    t.get("average_feedback_rating") if t.get("average_feedback_rating") is not None else "N/A",
                    f"{t.get('average_feedback_percentage')}%" if t.get("average_feedback_percentage") is not None else "N/A",
                    t.get("help_requests_received"),
                    t.get("help_requests_resolved"),
                    t.get("help_requests_pending"),
                ])

        elif report_type == ReportType.STUDENT_HELP_REQUESTS:
            ws.cell(row=current_row, column=1, value=f"Total: {data.get('total_help_requests')} | Pending: {data.get('pending_count')} | In Progress: {data.get('in_progress_count')} | Resolved: {data.get('resolved_count')}").font = Font(bold=True)
            current_row += 2
            headers = ["ID", "Status", "Created At", "Student ID", "Student Name", "Phone", "Batch", "Teacher", "Session Date", "Topic", "Student Message", "Teacher Note", "Resolved At", "Resolved By"]
            for hr in data.get("help_requests", []):
                rows.append([
                    hr.get("id"),
                    hr.get("status"),
                    hr.get("created_at"),
                    hr.get("student_id_number"),
                    hr.get("student_name"),
                    hr.get("phone"),
                    hr.get("batch_name"),
                    hr.get("teacher_name"),
                    hr.get("session_date"),
                    hr.get("topic_title"),
                    hr.get("student_message"),
                    hr.get("teacher_note"),
                    hr.get("resolved_at") or "",
                    hr.get("resolved_by") or "",
                ])

        elif report_type == ReportType.REPEATED_ABSENCES:
            ws.cell(row=current_row, column=1, value=f"Consecutive Threshold: {data.get('threshold_consecutive')} | Total Threshold: {data.get('threshold_total')} | Flagged Students: {data.get('total_flagged_students')}").font = Font(bold=True)
            current_row += 2
            headers = ["Student ID", "Reg No", "Student Name", "Phone", "Batch", "Consecutive", "Total", "Sessions", "Attendance %", "Last Absent", "Reasons"]
            for st in data.get("flagged_students", []):
                rows.append([
                    st.get("student_id_number"),
                    st.get("registration_no"),
                    st.get("student_name"),
                    st.get("phone"),
                    st.get("batch_name"),
                    st.get("consecutive_absences"),
                    st.get("total_absences"),
                    st.get("total_sessions"),
                    f"{st.get('attendance_percentage')}%" if st.get("attendance_percentage") is not None else "N/A",
                    st.get("last_absent_date") or "",
                    "; ".join(st.get("flagged_reasons", [])),
                ])

        elif report_type == ReportType.COORDINATOR_DASHBOARD:
            lp = data.get("overall_learning_progress", {})
            ws.cell(row=current_row, column=1, value=f"Total Students: {data.get('total_students')} | Active Batches: {data.get('total_active_batches')} | Teachers: {data.get('total_teachers')} | Today's Classes: {data.get('todays_classes')}").font = Font(bold=True)
            ws.cell(row=current_row+1, column=1, value=f"Attendance: {data.get('overall_attendance_percentage')}% | Learning Progress: {lp.get('average_rating')} / 5 ({lp.get('average_percentage')}%) | Total HR: {data.get('total_help_requests')} (Pending: {data.get('pending_help_requests')})").font = Font(bold=True)
            current_row += 3
            headers = ["Batch Name", "Batch #", "Course", "Students", "Attendance %", "Avg Rating", "Avg %", "Pending HR"]
            for b in data.get("batch_wise_performance", []):
                rows.append([
                    b.get("batch_name"),
                    b.get("batch_number"),
                    b.get("course_name"),
                    b.get("student_count"),
                    f"{b.get('attendance_percentage')}%" if b.get("attendance_percentage") is not None else "N/A",
                    b.get("average_rating") if b.get("average_rating") is not None else "N/A",
                    f"{b.get('average_percentage')}%" if b.get("average_percentage") is not None else "N/A",
                    b.get("pending_help_requests"),
                ])

        # Write Table Headers
        if headers:
            ws.row_dimensions[current_row].height = 24
            for col_num, h_text in enumerate(headers, 1):
                c = ws.cell(row=current_row, column=col_num, value=h_text)
                c.font = tbl_hdr_font
                c.fill = tbl_hdr_fill
                c.alignment = align_center
                c.border = thin_border

            # Write Table Rows
            for r_idx, r_vals in enumerate(rows, start=current_row + 1):
                ws.row_dimensions[r_idx].height = 20
                is_zebra = (r_idx % 2 == 0)
                for col_num, val in enumerate(r_vals, 1):
                    c = ws.cell(row=r_idx, column=col_num, value=val)
                    c.font = regular_font
                    c.border = thin_border
                    if is_zebra:
                        c.fill = zebra_fill
                    if isinstance(val, (int, float)):
                        c.alignment = align_right
                    else:
                        c.alignment = align_left

        # Auto-adjust column widths
        for col in ws.columns:
            max_len = 0
            col_letter = get_column_letter(col[0].column)
            for cell in col:
                # ignore merged title cells for width calculation
                if cell.row in [1, 2]:
                    continue
                val_str = str(cell.value or "")
                if len(val_str) > max_len:
                    max_len = len(val_str)
            ws.column_dimensions[col_letter].width = max(max_len + 3, 12)

        output = io.BytesIO()
        wb.save(output)
        output.seek(0)
        return output
