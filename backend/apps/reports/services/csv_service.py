import csv
import io
from typing import Any, Dict, List, Optional
from apps.reports.constants import REPORT_NAMES, ReportType
from apps.reports.services.docx_service import WordExportService


class CSVExportService:
    """
    Generates UTF-8 BOM compliant CSV spreadsheets for all ASSDI reports.
    UTF-8 BOM ensures seamless opening in Excel on Windows/Mac without Bengali character corruption.
    """

    @classmethod
    def generate_csv(
        cls,
        report_type: str,
        data: Dict[str, Any],
        user_name: str = "Staff",
        filters: Optional[Dict[str, Any]] = None,
    ) -> io.BytesIO:
        buffer = io.StringIO()
        # Write UTF-8 BOM
        buffer.write('\ufeff')
        writer = csv.writer(buffer)

        report_title = REPORT_NAMES.get(report_type, report_type.replace("_", " ").title())

        # Header metadata
        writer.writerow(["As-Sunnah Skill Development Institute (ASSDI)"])
        writer.writerow([f"Report: {report_title}"])
        writer.writerow([f"Generated By: {user_name}", f"Filters: {filters if filters else 'All'}"])
        writer.writerow([]) # Blank line

        # Use extraction logic from WordExportService
        # If we check how docx_service extracts headers and rows:
        headers, rows = cls._extract_csv_rows(report_type, data)

        if headers:
            writer.writerow(headers)
            for row in rows:
                writer.writerow(row)

        mem_buffer = io.BytesIO()
        mem_buffer.write(buffer.getvalue().encode('utf-8'))
        mem_buffer.seek(0)
        return mem_buffer

    @classmethod
    def _extract_csv_rows(cls, report_type: str, data: Dict[str, Any]):
        headers = []
        rows = []

        if report_type == ReportType.DAILY_ATTENDANCE:
            headers = ["Session ID", "Batch", "Subject", "Topic", "Teacher", "Start", "End", "Present", "Late", "Absent", "Leave", "Total", "Attendance %"]
            for s in data.get("sessions", []):
                rows.append([
                    s.get("session_id"), s.get("batch_name"), s.get("subject_name"),
                    s.get("topic_title") or "-", s.get("teacher_name"), s.get("start_time"),
                    s.get("end_time"), s.get("present_count"), s.get("late_count"),
                    s.get("absent_count"), s.get("approved_leave_count"), s.get("total_records"),
                    f"{s.get('attendance_percentage', 0.0)}%" if s.get("attendance_percentage") is not None else "N/A"
                ])

        elif report_type == ReportType.DAILY_LEARNING_PROGRESS:
            headers = ["Session ID", "Batch", "Subject", "Topic", "Teacher", "Feedbacks", "Pending", "Avg Rating", "Avg %", "Needs Help"]
            for s in data.get("sessions", []):
                rows.append([
                    s.get("session_id"), s.get("batch_name"), s.get("subject_name"),
                    s.get("topic_title") or "-", s.get("teacher_name"), s.get("feedback_count"),
                    s.get("pending_feedback_count"), s.get("average_rating") or "N/A",
                    f"{s.get('average_percentage')}%" if s.get("average_percentage") is not None else "N/A",
                    s.get("needs_help_count")
                ])

        elif report_type == ReportType.MONTHLY_STUDENT_PERFORMANCE:
            headers = ["Student ID", "Reg No", "Student Name", "Phone", "Sessions", "Present", "Absent", "Attendance %", "Feedbacks", "Avg Rating", "Avg %", "Status"]
            for st in data.get("students", []):
                rows.append([
                    st.get("student_id_number"), st.get("registration_no"), st.get("student_name"),
                    st.get("phone"), st.get("total_sessions"), st.get("present_count"),
                    st.get("absent_count"), f"{st.get('attendance_percentage')}%" if st.get("attendance_percentage") is not None else "N/A",
                    st.get("feedback_count"), st.get("average_rating") or "N/A",
                    f"{st.get('average_percentage')}%" if st.get("average_percentage") is not None else "N/A",
                    st.get("status")
                ])

        else:
            headers = ["Indicator", "Value"]
            for k, v in data.items():
                if isinstance(v, (str, int, float, bool)):
                    rows.append([str(k).replace("_", " ").title(), str(v)])

        return headers, rows
