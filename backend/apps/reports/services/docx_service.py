import io
from typing import Any, Dict, List, Optional
import docx
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT, WD_ALIGN_VERTICAL
from docx.oxml import OxmlElement, parse_xml
from docx.oxml.ns import nsdecls, qn

from apps.reports.constants import REPORT_NAMES, ReportType


class WordExportService:
    """
    Generates professional, branded Microsoft Word (.docx) documents for ASSDI reports.
    """

    COLOR_PRIMARY = RGBColor(27, 77, 62)     # #1B4D3E
    COLOR_GOLD = RGBColor(197, 160, 89)      # #C5A059
    COLOR_DARK = RGBColor(31, 41, 55)        # #1F2937
    COLOR_MUTED = RGBColor(107, 114, 128)    # #6B7280

    @classmethod
    def _set_cell_background(cls, cell, hex_color: str):
        shading = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{hex_color}"/>')
        cell._tc.get_or_add_tcPr().append(shading)

    @classmethod
    def _set_cell_margins(cls, cell, top=100, bottom=100, left=150, right=150):
        tcPr = cell._tc.get_or_add_tcPr()
        tcMar = OxmlElement('w:tcMar')
        for m, val in [('top', top), ('bottom', bottom), ('left', left), ('right', right)]:
            node = OxmlElement(f'w:{m}')
            node.set(qn('w:w'), str(val))
            node.set(qn('w:type'), 'dxa')
            tcMar.append(node)
        tcPr.append(tcMar)

    @classmethod
    def generate_docx(
        cls,
        report_type: str,
        data: Dict[str, Any],
        user_name: str = "Staff",
        filters: Optional[Dict[str, Any]] = None,
    ) -> io.BytesIO:
        doc = Document()

        # Page Setup: Standard A4 margins
        sections = doc.sections
        for section in sections:
            section.top_margin = Inches(0.75)
            section.bottom_margin = Inches(0.75)
            section.left_margin = Inches(0.75)
            section.right_margin = Inches(0.75)

        report_title = REPORT_NAMES.get(report_type, report_type.replace("_", " ").title())

        # 1. Main Header Title
        title_p = doc.add_paragraph()
        title_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        title_run = title_p.add_run("As-Sunnah Skill Development Institute (ASSDI)\n")
        title_run.font.name = "Arial"
        title_run.font.size = Pt(16)
        title_run.font.bold = True
        title_run.font.color.rgb = cls.COLOR_PRIMARY

        sub_run = title_p.add_run(f"Official Institutional Report: {report_title}")
        sub_run.font.name = "Arial"
        sub_run.font.size = Pt(13)
        sub_run.font.bold = True
        sub_run.font.color.rgb = cls.COLOR_GOLD

        # 2. Metadata Box / Callout
        meta_table = doc.add_table(rows=1, cols=2)
        meta_table.alignment = WD_TABLE_ALIGNMENT.CENTER
        meta_table.autofit = True
        cell_l, cell_r = meta_table.rows[0].cells
        cls._set_cell_background(cell_l, "F4F6F5")
        cls._set_cell_background(cell_r, "F4F6F5")
        cls._set_cell_margins(cell_l, top=120, bottom=120, left=180, right=180)
        cls._set_cell_margins(cell_r, top=120, bottom=120, left=180, right=180)

        p_l = cell_l.paragraphs[0]
        r1 = p_l.add_run("Generated By: ")
        r1.font.bold = True
        r1.font.size = Pt(9.5)
        r2 = p_l.add_run(f"{user_name}\n")
        r2.font.size = Pt(9.5)
        r3 = p_l.add_run("Status: ")
        r3.font.bold = True
        r3.font.size = Pt(9.5)
        p_l.add_run("Official & Verified (ASSDI System)").font.size = Pt(9.5)

        p_r = cell_r.paragraphs[0]
        p_r.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        r4 = p_r.add_run("Applied Filters: ")
        r4.font.bold = True
        r4.font.size = Pt(9.5)
        r5 = p_r.add_run(f"{filters if filters else 'All Records'}\n")
        r5.font.size = Pt(9.5)
        r6 = p_r.add_run("Format: ")
        r6.font.bold = True
        r6.font.size = Pt(9.5)
        p_r.add_run("Microsoft Word (.docx)").font.size = Pt(9.5)

        doc.add_paragraph() # Spacing

        # 3. Extract Headers, Summary & Rows from Data
        headers: List[str] = []
        rows: List[List[Any]] = []
        summary_text = ""

        if report_type == ReportType.DAILY_ATTENDANCE:
            summary_text = f"Report Date: {data.get('report_date')} | Total Sessions: {data.get('total_sessions')} | Overall Attendance: {data.get('attendance_percentage', 'N/A')}%"
            headers = ["Session ID", "Batch", "Subject", "Topic", "Teacher", "Start", "End", "Present", "Late", "Absent", "Leave", "Total", "Attendance %"]
            for s in data.get("sessions", []):
                rows.append([
                    str(s.get("session_id")), str(s.get("batch_name")), str(s.get("subject_name")),
                    str(s.get("topic_title") or "-"), str(s.get("teacher_name")), str(s.get("start_time")),
                    str(s.get("end_time")), str(s.get("present_count")), str(s.get("late_count")),
                    str(s.get("absent_count")), str(s.get("approved_leave_count")), str(s.get("total_records")),
                    f"{s.get('attendance_percentage', 0.0)}%" if s.get("attendance_percentage") is not None else "N/A"
                ])

        elif report_type == ReportType.DAILY_LEARNING_PROGRESS:
            summary_text = f"Report Date: {data.get('report_date')} | Total Feedbacks: {data.get('total_feedbacks')} | Average Rating: {data.get('average_rating')} / 5 ({data.get('average_percentage')}%)"
            headers = ["Session ID", "Batch", "Subject", "Topic", "Teacher", "Feedbacks", "Pending", "Avg Rating", "Avg %", "Needs Help"]
            for s in data.get("sessions", []):
                rows.append([
                    str(s.get("session_id")), str(s.get("batch_name")), str(s.get("subject_name")),
                    str(s.get("topic_title") or "-"), str(s.get("teacher_name")), str(s.get("feedback_count")),
                    str(s.get("pending_feedback_count")), str(s.get("average_rating") or "N/A"),
                    f"{s.get('average_percentage')}%" if s.get("average_percentage") is not None else "N/A",
                    str(s.get("needs_help_count"))
                ])

        elif report_type == ReportType.WEEKLY_PROGRESS:
            period = data.get("period", {})
            summary_text = f"Period: {period.get('start_date')} to {period.get('end_date')} | Total Classes: {data.get('total_classes')} | Attendance: {data.get('attendance_summary', {}).get('attendance_percentage')}%"
            headers = ["Date", "Day", "Classes", "Attendance %", "Average Rating", "Average %"]
            for d in data.get("daily_breakdown", []):
                rows.append([
                    str(d.get("date")), str(d.get("day_name")), str(d.get("classes_count")),
                    f"{d.get('attendance_percentage')}%" if d.get("attendance_percentage") is not None else "N/A",
                    str(d.get("average_rating") or "N/A"),
                    f"{d.get('average_percentage')}%" if d.get("average_percentage") is not None else "N/A"
                ])

        elif report_type == ReportType.MONTHLY_STUDENT_PERFORMANCE:
            summary_text = f"Month: {data.get('year')}-{data.get('month', 1):02d} | Batch: {data.get('batch_name')} | Students: {data.get('total_students')}"
            headers = ["Student ID", "Reg No", "Student Name", "Sessions", "Present", "Absent", "Attendance %", "Avg Rating", "Status"]
            for st in data.get("students", []):
                rows.append([
                    str(st.get("student_id_number")), str(st.get("registration_no")), str(st.get("student_name")),
                    str(st.get("total_sessions")), str(st.get("present_count")), str(st.get("absent_count")),
                    f"{st.get('attendance_percentage')}%" if st.get("attendance_percentage") is not None else "N/A",
                    str(st.get("average_rating") or "N/A"), str(st.get("status"))
                ])

        elif report_type == ReportType.BATCH_WISE_PERFORMANCE:
            summary_text = "Comparative batch metrics across courses and active campuses."
            headers = ["Batch ID", "Batch Name", "Course", "Campus", "Status", "Students", "Attendance %", "Avg %", "Help Requests"]
            for b in data.get("batches", []):
                rows.append([
                    str(b.get("batch_id")), str(b.get("batch_name")), str(b.get("course_name")),
                    str(b.get("campus_name")), str(b.get("status")), str(b.get("student_count")),
                    f"{b.get('attendance_percentage')}%" if b.get("attendance_percentage") is not None else "N/A",
                    f"{b.get('average_percentage')}%" if b.get("average_percentage") is not None else "N/A",
                    str(b.get("total_help_requests"))
                ])

        elif report_type == ReportType.TOPIC_WISE_UNDERSTANDING:
            summary_text = "Curriculum topics understanding and student feedback bands."
            headers = ["Topic ID", "Topic Title", "Subject", "Course", "Sessions", "Feedbacks", "Avg Rating", "Avg %", "Needs Help"]
            for t in data.get("topics", []):
                rows.append([
                    str(t.get("topic_id")), str(t.get("topic_title")), str(t.get("subject_name")),
                    str(t.get("course_name")), str(t.get("total_sessions")), str(t.get("total_feedbacks")),
                    str(t.get("average_rating") or "N/A"),
                    f"{t.get('average_percentage')}%" if t.get("average_percentage") is not None else "N/A",
                    str(t.get("needs_help_count"))
                ])

        elif report_type == ReportType.TEACHER_WISE:
            summary_text = "Faculty teaching load, student comprehension ratings, and help request resolution."
            headers = ["Teacher Name", "Login ID", "Assigned Batches", "Classes Conducted", "Attendance %", "Avg Rating", "HR Resolved"]
            for t in data.get("teachers", []):
                rows.append([
                    str(t.get("teacher_name")), str(t.get("login_id")), str(t.get("assigned_batches_count")),
                    str(t.get("classes_conducted")),
                    f"{t.get('attendance_percentage_in_classes')}%" if t.get("attendance_percentage_in_classes") is not None else "N/A",
                    str(t.get("average_feedback_rating") or "N/A"),
                    str(t.get("help_requests_resolved"))
                ])

        elif report_type == ReportType.STUDENT_HELP_REQUESTS:
            summary_text = f"Total Requests: {data.get('total_help_requests')} | Pending: {data.get('pending_count')} | In Progress: {data.get('in_progress_count')} | Resolved: {data.get('resolved_count')}"
            headers = ["ID", "Status", "Student ID", "Student Name", "Batch", "Teacher", "Topic", "Student Message", "Teacher Note"]
            for hr in data.get("help_requests", []):
                rows.append([
                    str(hr.get("id")), str(hr.get("status")), str(hr.get("student_id_number")),
                    str(hr.get("student_name")), str(hr.get("batch_name")), str(hr.get("teacher_name")),
                    str(hr.get("topic_title")), str(hr.get("student_message") or "-"), str(hr.get("teacher_note") or "-")
                ])

        elif report_type == ReportType.REPEATED_ABSENCES:
            summary_text = f"Consecutive Threshold: {data.get('threshold_consecutive')} | Total Threshold: {data.get('threshold_total')} | Flagged At-Risk Students: {data.get('total_flagged_students')}"
            headers = ["Student ID", "Reg No", "Student Name", "Phone", "Batch", "Consecutive", "Total", "Sessions", "Attendance %"]
            for st in data.get("flagged_students", []):
                rows.append([
                    str(st.get("student_id_number")), str(st.get("registration_no")), str(st.get("student_name")),
                    str(st.get("phone")), str(st.get("batch_name")), str(st.get("consecutive_absences")),
                    str(st.get("total_absences")), str(st.get("total_sessions")),
                    f"{st.get('attendance_percentage')}%" if st.get("attendance_percentage") is not None else "N/A"
                ])

        else:
            summary_text = "Executive performance metrics and institutional indicators."
            headers = ["Metric Key", "Indicator Value"]
            for k, v in data.items():
                if isinstance(v, (str, int, float, bool)):
                    rows.append([str(k).replace("_", " ").title(), str(v)])

        # 4. Summary Callout Box
        if summary_text:
            sum_p = doc.add_paragraph()
            sum_p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            r_sum = sum_p.add_run(f"Executive Summary: {summary_text}")
            r_sum.font.name = "Arial"
            r_sum.font.size = Pt(10.5)
            r_sum.font.bold = True
            r_sum.font.color.rgb = cls.COLOR_PRIMARY
            doc.add_paragraph()

        # 5. Render Data Table
        if headers:
            table = doc.add_table(rows=len(rows) + 1, cols=len(headers))
            table.alignment = WD_TABLE_ALIGNMENT.CENTER
            table.autofit = True

            # Style Header Row
            hdr_cells = table.rows[0].cells
            for idx, h in enumerate(headers):
                cell = hdr_cells[idx]
                cell.text = h
                cls._set_cell_background(cell, "1B4D3E")
                cls._set_cell_margins(cell, top=120, bottom=120, left=120, right=120)
                p = cell.paragraphs[0]
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                for run in p.runs:
                    run.font.name = "Arial"
                    run.font.size = Pt(9)
                    run.font.bold = True
                    run.font.color.rgb = RGBColor(255, 255, 255)

            # Style Data Rows
            for row_idx, row_data in enumerate(rows):
                row_cells = table.rows[row_idx + 1].cells
                bg_color = "F7FBF9" if row_idx % 2 == 1 else "FFFFFF"
                for col_idx, val in enumerate(row_data):
                    cell = row_cells[col_idx]
                    cell.text = str(val) if val is not None else "-"
                    cls._set_cell_background(cell, bg_color)
                    cls._set_cell_margins(cell, top=80, bottom=80, left=100, right=100)
                    p = cell.paragraphs[0]
                    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
                    for run in p.runs:
                        run.font.name = "Arial"
                        run.font.size = Pt(8.5)
                        run.font.color.rgb = cls.COLOR_DARK

        # 6. Official Footer
        doc.add_paragraph()
        footer_p = doc.add_paragraph()
        footer_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        foot_run = footer_p.add_run(
            "Official Institutional Document | As-Sunnah Skill Development Institute (ASSDI)\n"
            "Dhaka, Bangladesh | Verified by Academic & Administration Registry"
        )
        foot_run.font.name = "Arial"
        foot_run.font.size = Pt(8)
        foot_run.font.italic = True
        foot_run.font.color.rgb = cls.COLOR_MUTED

        buffer = io.BytesIO()
        doc.save(buffer)
        buffer.seek(0)
        return buffer
