import io
import os
import zoneinfo
from typing import Any, Dict, List, Optional

from django.utils import timezone
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import (
    HRFlowable,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from apps.reports.constants import REPORT_NAMES, ReportType

# Font registration with fail-safe fallbacks
FONT_NAME = "Helvetica"
FONT_NAME_BOLD = "Helvetica-Bold"

BENGALI_FONT_PATH = "/usr/share/fonts/truetype/noto/NotoSansBengali-Regular.ttf"
DEJAVU_FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
DEJAVU_BOLD_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

try:
    if os.path.exists(BENGALI_FONT_PATH):
        pdfmetrics.registerFont(TTFont("NotoSansBengali", BENGALI_FONT_PATH))
        FONT_NAME = "NotoSansBengali"
        FONT_NAME_BOLD = "NotoSansBengali"
    elif os.path.exists(DEJAVU_FONT_PATH):
        pdfmetrics.registerFont(TTFont("DejaVuSans", DEJAVU_FONT_PATH))
        if os.path.exists(DEJAVU_BOLD_PATH):
            pdfmetrics.registerFont(TTFont("DejaVuSans-Bold", DEJAVU_BOLD_PATH))
            FONT_NAME_BOLD = "DejaVuSans-Bold"
        else:
            FONT_NAME_BOLD = "DejaVuSans"
        FONT_NAME = "DejaVuSans"
except Exception:
    FONT_NAME = "Helvetica"
    FONT_NAME_BOLD = "Helvetica-Bold"


class NumberedCanvas:
    """Two-pass canvas for Page X of Y footers."""
    pass


class PDFExportService:
    HEADER_COLOR = colors.HexColor("#1B4D3E")     # Deep Emerald
    SUB_HEADER_COLOR = colors.HexColor("#2D6A4F") # Medium Forest Green
    ZEBRA_COLOR = colors.HexColor("#F7FBF9")      # Light Tint
    BORDER_COLOR = colors.HexColor("#D1D5DB")     # Gray 300

    @classmethod
    def generate_pdf(
        cls,
        report_type: str,
        data: Dict[str, Any],
        user_name: str = "Staff",
        filters: Optional[Dict[str, Any]] = None,
    ) -> io.BytesIO:
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=landscape(A4),
            leftMargin=36,
            rightMargin=36,
            topMargin=36,
            bottomMargin=36,
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Heading1"],
            fontName=FONT_NAME_BOLD,
            fontSize=16,
            leading=20,
            textColor=cls.HEADER_COLOR,
            alignment=1,  # Center
        )
        subtitle_style = ParagraphStyle(
            "DocSubTitle",
            parent=styles["Heading2"],
            fontName=FONT_NAME_BOLD,
            fontSize=12,
            leading=16,
            textColor=cls.SUB_HEADER_COLOR,
            alignment=1,  # Center
        )
        meta_style = ParagraphStyle(
            "DocMeta",
            parent=styles["Normal"],
            fontName=FONT_NAME,
            fontSize=8,
            leading=11,
            textColor=colors.HexColor("#4B5563"),
            alignment=0,  # Left
        )
        th_style = ParagraphStyle(
            "TableHeader",
            parent=styles["Normal"],
            fontName=FONT_NAME_BOLD,
            fontSize=8,
            leading=10,
            textColor=colors.white,
            alignment=1,  # Center
        )
        td_style = ParagraphStyle(
            "TableCell",
            parent=styles["Normal"],
            fontName=FONT_NAME,
            fontSize=7,
            leading=9,
            textColor=colors.HexColor("#1F2937"),
            alignment=0,  # Left
        )
        td_center_style = ParagraphStyle(
            "TableCellCenter",
            parent=td_style,
            alignment=1,  # Center
        )

        elements: List[Any] = []

        # 1. Title Banner
        report_title = REPORT_NAMES.get(report_type, report_type.replace("_", " ").title())
        elements.append(Paragraph("As-Sunnah Skill Development Institute (ASSDI)", title_style))
        elements.append(Spacer(1, 4))
        elements.append(Paragraph(report_title, subtitle_style))
        elements.append(Spacer(1, 8))

        # 2. Metadata Block
        dhaka_tz = zoneinfo.ZoneInfo("Asia/Dhaka")
        now_str = timezone.now().astimezone(dhaka_tz).strftime("%Y-%m-%d %H:%M:%S (%Z)")
        filter_str = ", ".join([f"{k}: {v}" for k, v in (filters or {}).items()]) if filters else "None"
        meta_text = f"<b>Generated At:</b> {now_str} &nbsp;|&nbsp; <b>Generated By:</b> {user_name} &nbsp;|&nbsp; <b>Filters:</b> {filter_str}"
        elements.append(Paragraph(meta_text, meta_style))
        elements.append(Spacer(1, 8))
        elements.append(HRFlowable(width="100%", thickness=1, color=cls.BORDER_COLOR, spaceBefore=2, spaceAfter=8))

        # 3. Headers and Rows extracted based on report_type
        headers: List[str] = []
        rows: List[List[str]] = []

        if report_type == ReportType.DAILY_ATTENDANCE:
            summary = f"<b>Date:</b> {data.get('report_date')} &nbsp;|&nbsp; <b>Total Sessions:</b> {data.get('total_sessions')} &nbsp;|&nbsp; <b>Overall Attendance:</b> {data.get('attendance_percentage', 'N/A')}%"
            elements.append(Paragraph(summary, meta_style))
            elements.append(Spacer(1, 6))
            headers = ["Session ID", "Batch", "Subject", "Topic", "Teacher", "Time", "Present", "Late", "Absent", "Leave", "Att %"]
            for s in data.get("sessions", []):
                rows.append([
                    str(s.get("session_id")),
                    str(s.get("batch_name")),
                    str(s.get("subject_name")),
                    str(s.get("topic_title")),
                    str(s.get("teacher_name")),
                    f"{s.get('start_time')}-{s.get('end_time')}",
                    str(s.get("present_count")),
                    str(s.get("late_count")),
                    str(s.get("absent_count")),
                    str(s.get("approved_leave_count")),
                    f"{s.get('attendance_percentage', 0.0)}%" if s.get("attendance_percentage") is not None else "N/A",
                ])

        elif report_type == ReportType.DAILY_LEARNING_PROGRESS:
            summary = f"<b>Date:</b> {data.get('report_date')} &nbsp;|&nbsp; <b>Total Feedbacks:</b> {data.get('total_feedbacks')} &nbsp;|&nbsp; <b>Avg Rating:</b> {data.get('average_rating')} / 5 ({data.get('average_percentage')}%)"
            elements.append(Paragraph(summary, meta_style))
            elements.append(Spacer(1, 6))
            headers = ["Session ID", "Batch", "Subject", "Topic", "Teacher", "Feedbacks", "Pending", "Avg Rating", "Avg %", "Needs Help"]
            for s in data.get("sessions", []):
                rows.append([
                    str(s.get("session_id")),
                    str(s.get("batch_name")),
                    str(s.get("subject_name")),
                    str(s.get("topic_title")),
                    str(s.get("teacher_name")),
                    str(s.get("feedback_count")),
                    str(s.get("pending_feedback_count")),
                    str(s.get("average_rating") if s.get("average_rating") is not None else "N/A"),
                    f"{s.get('average_percentage')}%" if s.get("average_percentage") is not None else "N/A",
                    str(s.get("needs_help_count")),
                ])

        elif report_type == ReportType.WEEKLY_PROGRESS:
            period = data.get("period", {})
            att_s = data.get("attendance_summary", {})
            learn_s = data.get("learning_summary", {})
            summary = f"<b>Period:</b> {period.get('start_date')} to {period.get('end_date')} &nbsp;|&nbsp; <b>Classes:</b> {data.get('total_classes')} &nbsp;|&nbsp; <b>Attendance:</b> {att_s.get('attendance_percentage')}% &nbsp;|&nbsp; <b>Learning:</b> {learn_s.get('average_percentage')}%"
            elements.append(Paragraph(summary, meta_style))
            elements.append(Spacer(1, 6))
            headers = ["Date", "Day", "Classes", "Attendance %", "Average Rating", "Average %"]
            for d in data.get("daily_breakdown", []):
                rows.append([
                    str(d.get("date")),
                    str(d.get("day_name")),
                    str(d.get("classes_count")),
                    f"{d.get('attendance_percentage')}%" if d.get("attendance_percentage") is not None else "N/A",
                    str(d.get("average_rating") if d.get("average_rating") is not None else "N/A"),
                    f"{d.get('average_percentage')}%" if d.get("average_percentage") is not None else "N/A",
                ])

        elif report_type == ReportType.MONTHLY_STUDENT_PERFORMANCE:
            summary = f"<b>Month:</b> {data.get('year')}-{data.get('month'):02d} &nbsp;|&nbsp; <b>Batch:</b> {data.get('batch_name')} &nbsp;|&nbsp; <b>Students:</b> {data.get('total_students')}"
            elements.append(Paragraph(summary, meta_style))
            elements.append(Spacer(1, 6))
            headers = ["Student ID", "Reg No", "Student Name", "Phone", "Sessions", "Present", "Late", "Absent", "Leave", "Att %", "Feedbacks", "Avg Rating", "Avg %", "Status"]
            for st in data.get("students", []):
                rows.append([
                    str(st.get("student_id_number")),
                    str(st.get("registration_no")),
                    str(st.get("student_name")),
                    str(st.get("phone")),
                    str(st.get("total_sessions")),
                    str(st.get("present_count")),
                    str(st.get("late_count")),
                    str(st.get("absent_count")),
                    str(st.get("approved_leave_count")),
                    f"{st.get('attendance_percentage')}%" if st.get("attendance_percentage") is not None else "N/A",
                    str(st.get("feedback_count")),
                    str(st.get("average_rating") if st.get("average_rating") is not None else "N/A"),
                    f"{st.get('average_percentage')}%" if st.get("average_percentage") is not None else "N/A",
                    str(st.get("status")),
                ])

        elif report_type == ReportType.BATCH_WISE_PERFORMANCE:
            headers = ["Batch Name", "Batch #", "Course", "Campus", "Status", "Students", "Classes", "Att %", "Avg Rating", "Avg %", "Help Req", "Pending HR"]
            for b in data.get("batches", []):
                rows.append([
                    str(b.get("batch_name")),
                    str(b.get("batch_number")),
                    str(b.get("course_name")),
                    str(b.get("campus_name")),
                    str(b.get("status")),
                    str(b.get("student_count")),
                    str(b.get("total_classes")),
                    f"{b.get('attendance_percentage')}%" if b.get("attendance_percentage") is not None else "N/A",
                    str(b.get("average_rating") if b.get("average_rating") is not None else "N/A"),
                    f"{b.get('average_percentage')}%" if b.get("average_percentage") is not None else "N/A",
                    str(b.get("total_help_requests")),
                    str(b.get("pending_help_requests")),
                ])

        elif report_type == ReportType.TOPIC_WISE_UNDERSTANDING:
            headers = ["Topic Title", "Subject", "Course", "Sessions", "Feedbacks", "Avg Rating", "Avg %", "Needs Help"]
            for t in data.get("topics", []):
                rows.append([
                    str(t.get("topic_title")),
                    str(t.get("subject_name")),
                    str(t.get("course_name")),
                    str(t.get("total_sessions")),
                    str(t.get("total_feedbacks")),
                    str(t.get("average_rating") if t.get("average_rating") is not None else "N/A"),
                    f"{t.get('average_percentage')}%" if t.get("average_percentage") is not None else "N/A",
                    str(t.get("needs_help_count")),
                ])

        elif report_type == ReportType.TEACHER_WISE:
            headers = ["Teacher Name", "Login ID", "Phone", "Assigned Batches", "Classes", "Att %", "Avg Rating", "Avg %", "HR Received", "HR Resolved"]
            for t in data.get("teachers", []):
                rows.append([
                    str(t.get("teacher_name")),
                    str(t.get("login_id")),
                    str(t.get("phone")),
                    str(t.get("assigned_batches_count")),
                    str(t.get("classes_conducted")),
                    f"{t.get('attendance_percentage_in_classes')}%" if t.get("attendance_percentage_in_classes") is not None else "N/A",
                    str(t.get("average_feedback_rating") if t.get("average_feedback_rating") is not None else "N/A"),
                    f"{t.get('average_feedback_percentage')}%" if t.get("average_feedback_percentage") is not None else "N/A",
                    str(t.get("help_requests_received")),
                    str(t.get("help_requests_resolved")),
                ])

        elif report_type == ReportType.STUDENT_HELP_REQUESTS:
            summary = f"<b>Total:</b> {data.get('total_help_requests')} &nbsp;|&nbsp; <b>Pending:</b> {data.get('pending_count')} &nbsp;|&nbsp; <b>In Progress:</b> {data.get('in_progress_count')} &nbsp;|&nbsp; <b>Resolved:</b> {data.get('resolved_count')}"
            elements.append(Paragraph(summary, meta_style))
            elements.append(Spacer(1, 6))
            headers = ["ID", "Status", "Date", "Student", "Phone", "Batch", "Teacher", "Topic", "Student Message", "Teacher Note"]
            for hr in data.get("help_requests", []):
                rows.append([
                    str(hr.get("id")),
                    str(hr.get("status")),
                    str(hr.get("session_date")),
                    f"{hr.get('student_id_number')}\n{hr.get('student_name')}",
                    str(hr.get("phone")),
                    str(hr.get("batch_name")),
                    str(hr.get("teacher_name")),
                    str(hr.get("topic_title")),
                    str(hr.get("student_message")),
                    str(hr.get("teacher_note")),
                ])

        elif report_type == ReportType.REPEATED_ABSENCES:
            summary = f"<b>Consecutive Threshold:</b> {data.get('threshold_consecutive')} &nbsp;|&nbsp; <b>Total Threshold:</b> {data.get('threshold_total')} &nbsp;|&nbsp; <b>Flagged Students:</b> {data.get('total_flagged_students')}"
            elements.append(Paragraph(summary, meta_style))
            elements.append(Spacer(1, 6))
            headers = ["Student ID", "Reg No", "Student Name", "Phone", "Batch", "Consecutive", "Total", "Sessions", "Att %", "Last Absent", "Reasons"]
            for st in data.get("flagged_students", []):
                rows.append([
                    str(st.get("student_id_number")),
                    str(st.get("registration_no")),
                    str(st.get("student_name")),
                    str(st.get("phone")),
                    str(st.get("batch_name")),
                    str(st.get("consecutive_absences")),
                    str(st.get("total_absences")),
                    str(st.get("total_sessions")),
                    f"{st.get('attendance_percentage')}%" if st.get("attendance_percentage") is not None else "N/A",
                    str(st.get("last_absent_date") or ""),
                    "; ".join(st.get("flagged_reasons", [])),
                ])

        elif report_type == ReportType.COORDINATOR_DASHBOARD:
            lp = data.get("overall_learning_progress", {})
            summary = f"<b>Total Students:</b> {data.get('total_students')} &nbsp;|&nbsp; <b>Active Batches:</b> {data.get('total_active_batches')} &nbsp;|&nbsp; <b>Teachers:</b> {data.get('total_teachers')} &nbsp;|&nbsp; <b>Today's Classes:</b> {data.get('todays_classes')}<br/><b>Attendance:</b> {data.get('overall_attendance_percentage')}% &nbsp;|&nbsp; <b>Learning:</b> {lp.get('average_rating')} / 5 ({lp.get('average_percentage')}%) &nbsp;|&nbsp; <b>Total Help Requests:</b> {data.get('total_help_requests')} (Pending: {data.get('pending_help_requests')})"
            elements.append(Paragraph(summary, meta_style))
            elements.append(Spacer(1, 8))
            headers = ["Batch Name", "Batch #", "Course", "Students", "Att %", "Avg Rating", "Avg %", "Pending HR"]
            for b in data.get("batch_wise_performance", []):
                rows.append([
                    str(b.get("batch_name")),
                    str(b.get("batch_number")),
                    str(b.get("course_name")),
                    str(b.get("student_count")),
                    f"{b.get('attendance_percentage')}%" if b.get("attendance_percentage") is not None else "N/A",
                    str(b.get("average_rating") if b.get("average_rating") is not None else "N/A"),
                    f"{b.get('average_percentage')}%" if b.get("average_percentage") is not None else "N/A",
                    str(b.get("pending_help_requests")),
                ])

        # Convert headers and rows to Paragraph flowables
        table_data = []
        if headers:
            header_row = [Paragraph(f"<b>{h}</b>", th_style) for h in headers]
            table_data.append(header_row)

            for r in rows:
                row_flowables = [Paragraph(str(val), td_style) for val in r]
                table_data.append(row_flowables)

            table = Table(table_data, repeatRows=1)
            t_style = TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), cls.HEADER_COLOR),
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("LEFTPADDING", (0, 0), (-1, -1), 4),
                ("RIGHTPADDING", (0, 0), (-1, -1), 4),
                ("GRID", (0, 0), (-1, -1), 0.5, cls.BORDER_COLOR),
            ])

            for i in range(1, len(table_data)):
                if i % 2 == 0:
                    t_style.add("BACKGROUND", (0, i), (-1, i), cls.ZEBRA_COLOR)

            table.setStyle(t_style)
            elements.append(table)

        # Build document
        doc.build(elements)
        buffer.seek(0)
        return buffer
